def unit(lang, value):
    return {"stringUnit": {"state": "translated", "value": value}}


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "Hearthside", "Resources", "Localizable.xcstrings")
    strings = {}
    for key in sorted(STRINGS):
        values = STRINGS[key]
        strings[key] = {"extractionState": "manual",
                        "localizations": {lang: unit(lang, values[i]) for i, lang in enumerate(LANGS)}}
    doc = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
    with open(out, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")
    print(f"Wrote {len(strings)} keys to {out}")


if __name__ == "__main__":
    main()
